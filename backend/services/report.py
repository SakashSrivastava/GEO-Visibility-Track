"""
PDF report export (Feature 5). Renders a stored analysis into a branded,
shareable PDF audit report using reportlab.
"""
from io import BytesIO
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle,
)

INK = colors.HexColor("#1a2030")
ACCENT = colors.HexColor("#4f8ef7")
MUTED = colors.HexColor("#8b95b0")


def _styles():
    ss = getSampleStyleSheet()
    ss.add(ParagraphStyle("H", fontName="Helvetica-Bold", fontSize=20, textColor=INK, spaceAfter=2))
    ss.add(ParagraphStyle("Sub", fontName="Helvetica", fontSize=9, textColor=MUTED, spaceAfter=14))
    ss.add(ParagraphStyle("Sec", fontName="Helvetica-Bold", fontSize=12, textColor=ACCENT, spaceBefore=14, spaceAfter=6))
    ss.add(ParagraphStyle("Body", fontName="Helvetica", fontSize=10, textColor=INK, leading=15))
    return ss


def _table(data, col_widths):
    t = Table(data, colWidths=col_widths, hAlign="LEFT")
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), INK),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d0d6e0")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f4f6fa")]),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return t


def build_report(results: dict, created_at: datetime | None = None) -> bytes:
    ss = _styles()
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=18 * mm, bottomMargin=18 * mm,
                            leftMargin=18 * mm, rightMargin=18 * mm, title="GEO Visibility Report")
    el = []
    brand = results.get("brand", "—")
    when = (created_at or datetime.utcnow()).strftime("%d %b %Y, %H:%M UTC")

    el.append(Paragraph("GEO Visibility Report", ss["H"]))
    el.append(Paragraph(f"Brand: <b>{brand}</b> &nbsp;·&nbsp; Region: {results.get('region','global')} "
                        f"&nbsp;·&nbsp; {when} &nbsp;·&nbsp; {results.get('run_count',0)} runs/prompt", ss["Sub"]))

    if results.get("summary"):
        el.append(Paragraph("Summary", ss["Sec"]))
        el.append(Paragraph(results["summary"], ss["Body"]))

    models = results.get("models", [])
    if models:
        el.append(Paragraph("Model Breakdown", ss["Sec"]))
        rows = [["Model", "Visibility", "±", "Appears", "Mentions", "Sentiment", "Rank"]]
        for m in models:
            if not m.get("ok", True):
                rows.append([m.get("name", "—"), "n/a", "", "", "", "unavailable", ""])
                continue
            rows.append([
                m.get("name", "—"), str(m.get("visibility_score", 0)), str(m.get("visibility_std", 0)),
                f"{int(m.get('appearance_rate', 0) * 100)}%", str(m.get("mention_count", 0)),
                m.get("sentiment_label", "—"), str(m.get("position_rank") or "—"),
            ])
        el.append(_table(rows, [34*mm, 20*mm, 12*mm, 18*mm, 20*mm, 24*mm, 14*mm]))

    sov = results.get("share_of_voice", [])
    if sov:
        el.append(Paragraph("Share of Voice", ss["Sec"]))
        rows = [["Brand", "Mentions", "Share"]] + [
            [s["name"] + (" (you)" if s.get("is_target") else ""), str(s["mentions"]), f"{s['share']}%"]
            for s in sov
        ]
        el.append(_table(rows, [80*mm, 30*mm, 30*mm]))

    cites = results.get("citations", [])
    if cites:
        el.append(Paragraph("Top Sources", ss["Sec"]))
        rows = [["Domain", "Citations", "Grounded", "Models"]] + [
            [c["domain"], str(c["count"]), "yes" if c.get("grounded") else "—", ", ".join(c.get("models", []))]
            for c in cites[:10]
        ]
        el.append(_table(rows, [55*mm, 22*mm, 22*mm, 45*mm]))

    geo = results.get("geo_visibility", [])
    if geo:
        el.append(Paragraph("Geographic Visibility", ss["Sec"]))
        rows = [["Region", "Score"]] + [[g["region"], str(g["score"])] for g in geo]
        el.append(_table(rows, [80*mm, 30*mm]))

    el.append(Spacer(1, 10 * mm))
    el.append(Paragraph("Generated by GEO Visibility Tracker — all metrics computed from real "
                        "model responses. See the project methodology for formulas.", ss["Sub"]))

    doc.build(el)
    buf.seek(0)
    return buf.read()
